#!/usr/bin/env python3
"""Regenerate WebGL FreeType isolation names after changing the vendored font library.

Use the WebGL build's freetype/libfreetype.a, not the combined bridge archive.
Both an original and an already isolated FreeType archive are accepted.
"""
import argparse
from pathlib import Path
import re
import subprocess

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--nm',required=True,type=Path)
parser.add_argument('--library',required=True,type=Path)
args=parser.parse_args()
raw=subprocess.check_output([str(args.nm),'--defined-only','--extern-only',str(args.library)],text=True)
names=sorted({line.split()[-1].removeprefix('URUI_FT_') for line in raw.splitlines()
              if re.fullmatch(r'[0-9a-fA-F]+ [A-Za-z] [A-Za-z_][A-Za-z_0-9]*',line)})
if not names or 'FT_Init_FreeType' not in names:
    raise SystemExit('Expected a complete FreeType archive with external symbols.')
path=Path(__file__).resolve().parents[1]/'Packages/com.fujisheng.urui/Native~/freetype_symbols.h'
path.write_text('// Generated by Tools/generate-font-symbol-prefix.py from the vendored FreeType archive.\n'
                "// WebGL statically links Unity's own FreeType; keep URUI's definitions and references private.\n"
                '#pragma once\n\n'+''.join(f'#define {name} URUI_FT_{name}\n'for name in names))
print(f'{len(names)} isolated FreeType symbols: {path}')
